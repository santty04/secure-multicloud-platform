import uuid
from typing import Literal

from pydantic import BaseModel, Field


class InfrastructureAdvisorRequest(BaseModel):
    ai_provider: Literal["ollama", "gemini"] = "ollama"
    request: str = Field(
        min_length=10,
        max_length=4000,
        description=("Natural language description of the infrastructure requirement."),
    )

    provider_preference: str | None = Field(
        default=None,
        max_length=32,
    )

    max_monthly_budget_usd: float | None = Field(
        default=None,
        gt=0,
    )

    environment: str = Field(
        default="dev",
        pattern=r"^(dev|test|prod)$",
    )

    requested_name: str | None = Field(
        default=None,
        min_length=1,
        max_length=64,
        pattern=r"^[A-Za-z0-9-]+$",
    )

    use_catalog_defaults: bool = False


class InfrastructureRecommendation(BaseModel):
    provider: str = Field(
        min_length=1,
        max_length=32,
    )

    requested_name: str | None = Field(
        default=None,
        min_length=1,
        max_length=64,
        pattern=r"^[A-Za-z0-9-]+$",
        description=(
            "Exact VM name explicitly requested by the user. "
            "Null when the user did not provide a name."
        ),
    )

    region: str = Field(
        min_length=1,
        max_length=64,
    )

    environment: str = Field(
        pattern=r"^(dev|test|prod)$",
    )

    instance_count: int = Field(
        ge=1,
        le=100,
    )

    instance_type: str = Field(
        min_length=1,
        max_length=64,
    )

    disk_type: str = Field(
        min_length=1,
        max_length=32,
    )

    disk_size_gb: int = Field(
        ge=1,
        le=4096,
    )

    public_ip: bool

    architecture_summary: str = Field(
        min_length=1,
        max_length=1500,
    )

    reason: str = Field(
        min_length=1,
        max_length=3000,
    )

    assumptions: list[str] = Field(
        default_factory=list,
        max_length=10,
    )

    risks: list[str] = Field(
        default_factory=list,
        max_length=10,
    )

    confidence: float = Field(
        ge=0,
        le=1,
    )


class InfrastructureAdvisorResponse(BaseModel):
    recommendation: InfrastructureRecommendation

    estimated_monthly_cost_usd: float | None = None

    pricing_status: str = "not_configured"

    ai_provider: str

    ai_model: str

    executable: bool = False


class AIHealthResponse(BaseModel):
    provider: str
    model: str
    available: bool


AIChatIntent = Literal[
    "general_question",
    "query_inventory",
    "get_vm_status",
    "start_vm",
    "stop_vm",
    "create_vm",
    "clarification",
]


class AIChatRequest(BaseModel):
    ai_provider: Literal["ollama", "gemini"] = "ollama"

    message: str = Field(
        min_length=2,
        max_length=4000,
        description="Natural language request for the multicloud assistant.",
    )


class AIChatDecision(BaseModel):
    """
    Structured output generated by the LLM.

    This describes what the AI understood.
    It does not authorize or execute any action.
    """

    intent: AIChatIntent

    message: str = Field(
        min_length=1,
        max_length=3000,
    )

    provider: Literal["azure", "aws"] | None = None

    requested_name: str | None = Field(
        default=None,
        min_length=1,
        max_length=64,
        pattern=r"^[A-Za-z0-9-]+$",
    )

    resource_id: uuid.UUID | None = None


class AIActionTarget(BaseModel):
    """
    Action validated by the backend and safe to present
    to the user for explicit confirmation.
    """

    action: Literal["start", "stop"]

    provider: Literal["azure", "aws"]

    resource_id: uuid.UUID

    resource_name: str

    current_status: str


class AIChatResponse(BaseModel):
    intent: AIChatIntent

    message: str

    provider: Literal["azure", "aws"] | None = None

    requested_name: str | None = None

    requires_confirmation: bool = False

    target_action: AIActionTarget | None = None

    ai_provider: str

    ai_model: str
